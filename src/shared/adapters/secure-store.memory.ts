import type { SecureStore } from '@/shared/ports/secure-store';

export function createMemorySecureStore(): SecureStore {
  const data = new Map<string, string>();
  return {
    async get(key) {
      return data.get(key) ?? null;
    },
    async set(key, value) {
      data.set(key, value);
    },
    async remove(key) {
      data.delete(key);
    },
  };
}
